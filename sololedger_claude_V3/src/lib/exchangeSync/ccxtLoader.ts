// ---- ccxt module handle (structural — avoids pulling ccxt types in eagerly) ----

interface CcxtExchangeCtor {
  new (config: Record<string, unknown>): unknown;
}

interface CcxtModule {
  [exchangeId: string]: CcxtExchangeCtor | unknown;
}

let ccxtPromise: Promise<CcxtModule> | null = null;
/** Resolved ccxt module, kept for synchronous instanceof checks (BUG-1). */
let ccxtModule: CcxtModule | null = null;

/** Lazily load (and memoize) the ccxt ESM bundle. */
export function loadCcxt(): Promise<CcxtModule> {
  if (!ccxtPromise) {
    ccxtPromise = (import('ccxt') as unknown as Promise<CcxtModule>).then((m) => {
      ccxtModule = m;
      return m;
    });
  }
  return ccxtPromise;
}

// ---- Structural shapes (subset of ccxt's unified structures we consume) ----

export interface UnifiedMarket {
  symbol: string;
  /** Exchange-native market id (e.g. 'BTCUSDT', 'BTC-USDT', 'XXBTZUSD'). */
  id?: string;
  base: string;
  quote: string;
  spot?: boolean;
  active?: boolean;
}

export interface UnifiedTrade {
  id?: string;
  order?: string;
  timestamp?: number;
  symbol?: string;
  side?: string;
  price?: number;
  amount?: number;
  cost?: number;
  fee?: { cost?: number; currency?: string };
  info?: Record<string, unknown>;
}

export interface UnifiedTransfer {
  id?: string;
  txid?: string;
  timestamp?: number;
  currency?: string;
  amount?: number;
  status?: string;
  type?: string;
  address?: string;
  addressTo?: string;
  addressFrom?: string;
  network?: string;
  fee?: { cost?: number; currency?: string };
  info?: Record<string, unknown>;
}

/** ccxt Balances structure (subset): per-asset {free, used, total} + 'total' dict. */
export interface UnifiedBalance {
  free?: Record<string, number | undefined>;
  used?: Record<string, number | undefined>;
  total?: Record<string, number | undefined>;
  info?: unknown;
  [asset: string]: unknown;
}

/** The subset of a ccxt exchange instance the engine drives. */
export interface ExchangeClient {
  id: string;
  markets?: Record<string, UnifiedMarket>;
  /** Enabled for HTX so pagination can use the raw response's final item before CCXT sorts parsed rows. */
  last_json_response?: unknown;
  /** BTC Markets exposes its native pagination cursors only in response headers. */
  last_response_headers?: Record<string, string>;
  /** Pinned MEXC public offline-symbol endpoint generated by CCXT. */
  spotPublicGetSymbolOffline?(params?: Record<string, unknown>): Promise<unknown>;
  loadMarkets(reload?: boolean): Promise<Record<string, UnifiedMarket>>;
  fetchBalance(params?: Record<string, unknown>): Promise<UnifiedBalance>;
  fetchMyTrades(
    symbol?: string,
    since?: number,
    limit?: number,
    params?: Record<string, unknown>
  ): Promise<UnifiedTrade[]>;
  fetchDeposits(
    code?: string,
    since?: number,
    limit?: number,
    params?: Record<string, unknown>
  ): Promise<UnifiedTransfer[]>;
  fetchWithdrawals(
    code?: string,
    since?: number,
    limit?: number,
    params?: Record<string, unknown>
  ): Promise<UnifiedTransfer[]>;
  /** Bitfinex exposes deposits and withdrawals through one Movements endpoint. */
  fetchDepositsWithdrawals?(
    code?: string,
    since?: number,
    limit?: number,
    params?: Record<string, unknown>
  ): Promise<UnifiedTransfer[]>;
  handleRestResponse(...args: unknown[]): unknown;
  fetch(url: string, method?: string, headers?: Record<string, string>, body?: string): Promise<unknown>;
}

